base = int(input("Informe um número para a base: "))
print(f"Base: {base} cm")

altura = int(input("Informe um número para a altura: "))
print(f"Altura: {altura} cm")

area = base * altura
perimetro = (base * 2) + (altura * 2)

print(f"A área é de {area} cm²")
print(f"O perímetro é de {perimetro} cm")